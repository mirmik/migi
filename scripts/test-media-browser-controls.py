"""Actual in-video controls and settings in inline, fullscreen and mobile views."""
import argparse
import os
import tempfile
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
from media_browser_controls import select_setting

parser=argparse.ArgumentParser()
parser.add_argument('--url',required=True)
args=parser.parse_args()
engine=os.environ.get('MIGI_BROWSER_ENGINE','chromium')
output=Path(tempfile.mkdtemp(prefix='migi-controls-'))
with sync_playwright() as p:
    options={'firefox_user_prefs':{'media.volume_scale':'0.0'}} if engine=='firefox' else {'executable_path':os.environ.get('MIGI_BROWSER_CHROMIUM'),'args':['--mute-audio']}
    browser=getattr(p,engine).launch(headless=True,**options)
    page=browser.new_page(viewport={'width':1280,'height':900}, screen={'width':1280,'height':900})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(args.url)
    page.get_by_role('button',name='Local album').click()
    page.wait_for_function('()=>document.querySelector("video").currentTime>0.1')
    assert page.locator('video').evaluate('v=>!v.controls')
    expect(page.locator('#video-settings')).to_be_hidden()
    page.locator('#video-stage').hover()
    page.get_by_role('button',name='Пауза',exact=True).click()
    assert page.locator('video').evaluate('v=>v.paused')
    page.get_by_role('button',name='Выключить звук',exact=True).click()
    assert page.locator('video').evaluate('v=>v.muted')
    page.locator('#video-stage').focus()
    page.keyboard.press('m')
    assert page.locator('video').evaluate('v=>!v.muted')
    seek=page.locator('#video-seek')
    box=seek.bounding_box()
    seek.click(position={'x':box['width']/2,'y':box['height']/2})
    page.wait_for_function('()=>{const v=document.querySelector("video");return !v.seeking && v.currentTime>3.5 && v.currentTime<4.5;}')
    assert page.locator('video').evaluate('v=>v.paused')
    page.locator('#video-stage').focus()
    page.keyboard.press('ArrowLeft')
    page.wait_for_function('()=>document.querySelector("video").currentTime<0.1')
    page.keyboard.press('ArrowRight')
    page.wait_for_function('()=>Math.abs(document.querySelector("video").currentTime-5)<0.2 && !document.querySelector("video").seeking')
    page.keyboard.press('f')
    page.wait_for_function('()=>document.fullscreenElement?.id==="video-stage"')
    select_setting(page,'#playback-speed',value='1.25')
    assert page.locator('#video-settings').evaluate('s=>document.fullscreenElement.contains(s)')
    assert page.locator('#video-fullscreen').evaluate('s=>{const b=s.getBoundingClientRect();return b.right<=innerWidth && b.bottom<=innerHeight;}')
    select_setting(page,'#audio-tracks',label='Английский')
    page.wait_for_function('()=>{const v=document.querySelector("video");return v.currentSrc.includes("audio=track-3") && v.readyState>=2 && !v.seeking;}')
    assert page.locator('video').evaluate('v=>v.paused && v.playbackRate===1.25 && Math.abs(v.currentTime-5)<0.2')
    select_setting(page,'#subtitles',label='English')
    page.wait_for_function('()=>document.querySelector("video track")?.track.activeCues?.[0]?.text==="Subtitle check"')
    assert page.locator('video').evaluate('v=>v.textTracks[0].activeCues[0].line!=="auto"')
    page.locator('#playback-speed').focus()
    page.keyboard.press('ArrowDown')
    assert page.locator('video').evaluate('v=>Math.abs(v.currentTime-5)<0.2')
    page.locator('#video-stage').screenshot(path=str(output/'fullscreen.png'))
    page.get_by_role('button',name='Закрыть настройки',exact=True).click()
    expect(page.locator('#video-settings')).to_be_hidden()
    page.get_by_role('button',name='Выйти из полного экрана',exact=True).click()
    page.wait_for_function('()=>document.fullscreenElement===null')
    page.set_viewport_size({'width':390,'height':844})
    select_setting(page,'#audio-tracks',label='Японский')
    select_setting(page,'#playback-speed',value='1')
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    assert page.locator('#video-settings').evaluate('s=>{const b=s.getBoundingClientRect(),v=document.querySelector("#video-stage").getBoundingClientRect();return b.left>=v.left && b.right<=v.right && b.bottom<=v.bottom;}')
    page.screenshot(path=str(output/'mobile.png'),full_page=True)
    page.get_by_role('button',name='Закрыть настройки',exact=True).click()
    page.locator('video').evaluate('v=>{v.currentTime=0;}')
    page.locator('#video-stage').hover()
    page.get_by_role('button',name='Воспроизвести',exact=True).click()
    page.mouse.move(0,0)
    page.wait_for_function('()=>document.querySelector("#video-stage").classList.contains("controls-hidden")',timeout=6000)
    assert page.locator('video').evaluate('v=>v.textTracks[0].activeCues[0].line==="auto"')
    page.locator('video').evaluate('v=>v.pause()')
    page.wait_for_function('()=>!document.querySelector("#video-stage").classList.contains("controls-hidden")')
    assert not errors,errors
    touch=browser.new_page(viewport={'width':390,'height':844},has_touch=True)
    touch.on('pageerror',lambda e:errors.append(str(e)))
    touch.goto(args.url)
    touch.get_by_role('button',name='Local album').tap()
    touch.wait_for_function('()=>document.querySelector("video").currentTime>0.1')
    touch.locator('video').tap(position={'x':20,'y':20})
    assert touch.locator('video').evaluate('v=>!v.paused')
    touch.get_by_role('button',name='Настройки плеера',exact=True).tap()
    touch.select_option('#playback-speed',value='1.5')
    touch.select_option('#audio-tracks',label='Английский')
    touch.wait_for_function('()=>{const v=document.querySelector("video");return v.currentSrc.includes("audio=track-3") && !v.paused && v.playbackRate===1.5;}')
    touch.get_by_role('button',name='Закрыть настройки',exact=True).tap()
    touch.get_by_role('button',name='Пауза',exact=True).tap()
    assert touch.locator('video').evaluate('v=>v.paused')
    assert not errors,errors
    browser.close()
print('PASS inline/fullscreen settings, play/pause, native range seek, mute, keyboard, focus, mobile layout and auto-hide. Screenshots:',output)
